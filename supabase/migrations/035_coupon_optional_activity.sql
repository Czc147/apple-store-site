-- 035: 券不再必须绑定活动（可创建「闲置券」，按需绑定活动 / 订阅）
--
-- 用户 2026-09-24 决定：券就是一张券，**活动和订阅是它的分发渠道**，不必二选一。
--
-- 为什么必须改：迁移 033 之后券有了第二条分发渠道（随卡券订阅发放），但
-- `activity_id` 仍是 NOT NULL —— 想做"订阅用户专属"的券就必须随便挂个活动，
-- 而一旦挂了活动，任何用户都能在活动页**免费领**它。等于专属券变成了公开券。
--
-- 改成可空之后：
--   - **不绑活动** = 闲置券：不在任何活动页展示、只能随订阅发放。
--     （活动页取券用的是 `in (activity_id, ...)`，NULL 天然不匹配任何活动，
--      所以那边**一行代码都不用改**。）
--   - **绑活动** = 照旧可被用户领取。
--   - 两者可同时成立：既在活动页可领，也随订阅发放。
--
-- ⚠️ 外键仍是 `on delete cascade`（老行为不动）：删活动会连它的券一起删。
--    而券现在可能还挂在订阅上，所以删活动的接口加了守卫
--    （见 src/app/api/activities/[id]/route.ts 的 DELETE：有订阅在用就拦下）。

alter table public.coupons
  alter column activity_id drop not null;

comment on column public.coupons.activity_id is
  '所属活动（分发渠道之一，迁移 035 起可空）：NULL = 闲置券，不在任何活动页展示、只能随订阅发放';
